package com.wxdgaming.batis.sql;

/**
 * CachedBeanRunner 在事务中的延迟写策略
 * <p>Write-Behind 的脏表是 JVM 全局的，而事务是线程级的，两者需要明确的协同规则。</p>
 * <p>问题具体化一下：延迟写只改缓存和脏表，不碰数据库。若它发生在事务里，
 * 回滚后数据库回到旧状态，脏表里的改动却还挂着，将来照样会被刷下去——
 * 于是"回滚掉的操作"重新出现。这个枚举就是把处理方式交给业务声明：
 * 要么当场写（脏表在事务里保持干净），要么直接拒绝，绝不默认放任。</p>
 * <p>取值时机是<em>每次延迟写调用</em>（{@code insertBean(bean,false)} 一类），
 * 非事务线程不受本枚举影响，仍按纯延迟语义执行。
 * 新增取值时记得 {@code CachedBeanRunner} 里的 switch 没有 default，
 * 编译期会强制要求表态，这是刻意留的护栏。</p>
 *
 * @author wxd-gaming(無心道, 15388152619)
 * @version 2026-10-09
 **/
public enum FlushMode {

    /**
     * 默认：事务内调用延迟写（insertBean(bean,false) 等）自动升级为事务内立即写；回滚时精确失效缓存
     * <p>选它当默认是因为对调用方最省心：延迟写的"少一次 IO"收益在事务里本来就不成立
     * （反正要当场落库），当场写还能让事务内的读看到自己刚写的值。</p>
     */
    TX_IMMEDIATE,
    /**
     * 加入事务：与 TX_IMMEDIATE 相同的写升级语义；事务内 flushAll() 与业务写同批提交，全有或全无
     * <p>两个取值当前行为一致（都当场写），差别只在意图声明：
     * TX_JOIN 表明这段代码是"有意把刷盘并进事务"的，读代码时不必再猜。
     * 事务内 {@code flushAll()} 的快照回填补偿对两者都生效，不取决于这里选哪个。</p>
     */
    TX_JOIN,
    /**
     * 挂起拒绝：事务内调用延迟写直接抛 IllegalTransactionStateException
     * <p>用于"这个业务不允许任何延迟写"的强约束场景：把可能的脏数据留在缓存里
     * 比失败更糟，所以宁可让调用点立刻炸出来。</p>
     */
    TX_SUSPEND,
    /**
     * 事务本地缓冲（规划中，暂未实现）：写入线程本地缓冲，提交时并入全局脏表
     * <p>当前使用会抛 UnsupportedOperationException。设计意图是让延迟写也能享受事务原子性，
     * 代价是要多一份线程级脏表与其到全局脏表的合并逻辑，尚未评估清楚，因此先占位。</p>
     */
    TX_PENDING_BUFFER

}
