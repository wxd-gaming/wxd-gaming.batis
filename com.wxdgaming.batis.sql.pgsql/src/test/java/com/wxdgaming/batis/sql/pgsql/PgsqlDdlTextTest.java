package com.wxdgaming.batis.sql.pgsql;

import com.wxdgaming.batis.model.ColumnInfo;
import com.wxdgaming.batis.model.TableInfo;
import com.wxdgaming.batis.parser.EntityParser;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * PG DDL 与 CRUD 语句文本单测
 * <p>不连库，只锁"发出去的语句长什么样"。真库行为由 {@code PgSchemaDriftIT} 与
 * {@code PgBeanRunnerIT} 负责，两者分工是刻意的：文本用例跑得快、能精确指出哪个子句写错，
 * 而 PG 的语法合法性（比如 IDENTITY 必须跟在类型之后）只有真库能证。</p>
 *
 * @author wxd-gaming(無心道, 15388152619)
 * @version 2026-10-14
 **/
class PgsqlDdlTextTest {

    private final PgsqlTableCreateHandler createHandler = PgsqlTableCreateHandler.INSTANCE;
    private final PgsqlBeanValueHandler valueHandler = new PgsqlBeanValueHandler();

    /** 取建表语句集（表 → 索引 → 注释） */
    private List<String> statements(Class<?> entityClass) {
        return createHandler.buildStatements(EntityParser.parse(entityClass),
                PgsqlColumnTypeDefHandler.INSTANCE);
    }

    /** 从 CREATE TABLE 正文里取出某一列的定义行（去掉行尾的子句分隔逗号） */
    private static String columnLine(String createTableSql, String columnName) {
        for (String line : createTableSql.split("\n")) {
            String stripped = line.strip();
            if (stripped.startsWith("\"" + columnName + "\"")) {
                return stripped.endsWith(",") ? stripped.substring(0, stripped.length() - 1) : stripped;
            }
        }
        return null;
    }

    // ==================== CREATE TABLE ====================

    /**
     * 用例①：建表被拆成"表 + 索引 + 注释"多条语句，且 MySQL 专有的尾巴一个都不带。
     * <p>断言 CREATE TABLE 里不含 {@code ENGINE}/{@code CHARSET}/内联 {@code INDEX}/内联 {@code COMMENT}：
     * 这四样在 PG 都是语法错误，而它们恰恰是 MySQL 建表语句的收尾部分——照抄过来只会得到
     * 一条"看着对、跑不了"的 DDL。数量断言（1 表 + 1 索引 + 1 表注释 + 8 列注释）则锁住
     * "每个声明的索引和每条注释都真的发出了语句"。</p>
     */
    @Test
    void createTableIsSplitIntoStatements() {
        List<String> statements = statements(PgAccountEntity.class);
        String create = statements.get(0);

        assertTrue(create.startsWith("CREATE TABLE IF NOT EXISTS \"t_pg_account\" ("), create);
        assertTrue(create.endsWith("\n)"), create);
        assertFalse(create.contains("ENGINE"), "PG 没有表级 ENGINE 子句");
        assertFalse(create.contains("CHARSET"), "PG 没有表级 CHARSET 子句");
        assertFalse(create.contains("INDEX"), "索引不能内联在 CREATE TABLE 里");
        assertFalse(create.contains("COMMENT"), "注释是独立对象，不能内联");
        assertTrue(create.contains("PRIMARY KEY (\"id\")"), create);

        // 索引与注释各自成语句
        assertEquals("CREATE UNIQUE INDEX IF NOT EXISTS \"idx_pg_account_name\" "
                + "ON \"t_pg_account\" (\"account_name\")", statements.get(1));
        assertEquals("COMMENT ON TABLE \"t_pg_account\" IS 'PG 账号表'", statements.get(2));
        assertEquals(1 + 1 + 1 + 8, statements.size(), "8 个字段都声明了注释");
        assertTrue(statements.contains("COMMENT ON COLUMN \"t_pg_account\".\"tags\" IS '标签'"));
    }

    /**
     * 用例②：列定义片段的子句顺序与形态。
     * <p>逐列抽查的要点：{@code NOT NULL} 在类型之后、{@code DEFAULT} 在可空性之后、
     * IDENTITY 只出现在"自增且是主键"的列上。字符串字面量默认值保留自带引号（{@code '2026-01-01'}），
     * 数字默认值保持裸写法（{@code 0.00}）——这是 {@link PgsqlSqlLiteral} 约定的书写口径，
     * 若在这里被二次加引号，元数据回读就永远对不上。</p>
     * <p>{@code frozen} 一行锁的是布尔特例：实体按 MySQL 习惯写 {@code defaultValue = "0"}，
     * 渲染必须折成 {@code DEFAULT false}——PG 的 boolean 列不接受整数默认值
     * （{@code DEFAULT 0} 是 42804，整条建表语句失败），而库端回读到的正是 {@code false}。</p>
     */
    @Test
    void columnDefinitionClauseOrder() {
        String create = statements(PgAccountEntity.class).get(0);

        assertEquals("\"account_name\" VARCHAR(64) NOT NULL", columnLine(create, "account_name"));
        assertEquals("\"balance\" NUMERIC(12,2) DEFAULT 0.00", columnLine(create, "balance"));
        assertEquals("\"vip_level\" INTEGER DEFAULT 0", columnLine(create, "vip_level"));
        assertEquals("\"frozen\" BOOLEAN DEFAULT false", columnLine(create, "frozen"));
        assertEquals("\"register_date\" DATE", columnLine(create, "register_date"));
        assertEquals("\"tags\" TEXT", columnLine(create, "tags"));
        // 主键被 EntityParser 强制置为 NOT NULL，IDENTITY 落在最后
        assertEquals("\"id\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY", columnLine(create, "id"));
    }

    /**
     * 用例③：IDENTITY 只给"自增主键"，非自增主键列保持手工赋值。
     * <p>动作：把 id 的生成策略改成 NONE（等价于手工指定主键的业务表）。
     * 断言：该列没有 IDENTITY 子句，但仍在表级 PRIMARY KEY 里。
     * 意义：PG 的 IDENTITY 会占序列号，给一个手工编号的列加上它等于每插一行就浪费一个序列值，
     * 而且 {@code ALWAYS} 语义下还会拒绝显式赋值。</p>
     */
    @Test
    void nonIdentityPrimaryKeyGetsNoIdentityClause() {
        TableInfo tableInfo = EntityParser.parse(PgOrderItemEntity.class);
        String create = createHandler.buildStatements(tableInfo, PgsqlColumnTypeDefHandler.INSTANCE).get(0);

        assertFalse(create.contains("GENERATED"), "复合主键未声明 IDENTITY，不应出现 IDENTITY 子句");
        assertTrue(create.contains("PRIMARY KEY (\"order_id\", \"sku_code\")"), create);
        assertEquals("\"sku_code\" VARCHAR(32) NOT NULL", columnLine(create, "sku_code"));
    }

    /**
     * 用例④：注释文本里的单引号只双写一次，绝不做反斜杠转义。
     * <p>PG 默认 {@code standard_conforming_strings=on}，反斜杠是普通字符：
     * 照 MySQL 的转义习惯写 {@code \'} 会把注释存成带反斜杠的字面值，事后看不出被改写过。</p>
     */
    @Test
    void commentQuotesAreDoubledNotBackslashEscaped() {
        TableInfo tableInfo = handTable("t_quote");
        tableInfo.setComment("表名 O'Brien");
        ColumnInfo col = handColumn("note", "TEXT");
        col.setComment("值里有换行\n和引号''");
        tableInfo.getColumns().put("note", col);

        List<String> statements = createHandler.buildStatements(tableInfo, PgsqlColumnTypeDefHandler.INSTANCE);
        assertEquals("COMMENT ON TABLE \"t_quote\" IS '表名 O''Brien'", statements.get(1));
        // 换行原样保留（标准 SQL 允许字面量内含裸换行），两个引号折成四个后再由外层引号收尾
        assertEquals("COMMENT ON COLUMN \"t_quote\".\"note\" IS '值里有换行\n和引号'''''", statements.get(2));
    }

    /**
     * 用例⑤：默认值书写越界时当场拒绝，而不是把半截 DDL 发到库端。
     * <p>断言 {@code "'; DROP TABLE t;--"} 这类输入抛 IllegalArgumentException：
     * 它既不是合法的字符串字面量（引号没成对），也不在裸字面量白名单里。</p>
     */
    @Test
    void unsafeDefaultValueFailsFast() {
        TableInfo tableInfo = handTable("t_bad_default");
        ColumnInfo col = handColumn("c", "TEXT");
        col.setDefaultValue("'''); DROP TABLE t_bad_default;--");
        tableInfo.getColumns().put("c", col);

        assertThrows(IllegalArgumentException.class,
                () -> createHandler.buildStatements(tableInfo, PgsqlColumnTypeDefHandler.INSTANCE));
    }

    /** 手工 TableInfo（EntityParser 之外的构造路径，columns 必须自己初始化） */
    private static TableInfo handTable(String tableName) {
        TableInfo tableInfo = new TableInfo();
        tableInfo.setTableName(tableName);
        tableInfo.setEntityClass(PgsqlDdlTextTest.class);
        tableInfo.setColumns(new LinkedHashMap<>());
        return tableInfo;
    }

    /** 手工列：只给建表必需的属性，其余走默认（可空、无注释、无默认值） */
    private static ColumnInfo handColumn(String columnName, String physicalType) {
        ColumnInfo col = new ColumnInfo();
        col.setColumnName(columnName);
        col.setType(physicalType);
        col.setNullable(true);
        return col;
    }

    // ==================== CRUD 语句文本 ====================

    /**
     * 用例⑥：INSERT 跳过自增主键列，其余列按声明顺序全参数化。
     * <p>断言 SQL 里没有 {@code "id"}，且参数个数 = 列数 - 1：占位符与参数是同一次遍历产出的，
     * 两边过滤谓词必须一致，错一位就会把账号名绑进余额列。</p>
     */
    @Test
    void insertSkipsIdentityColumn() {
        PgsqlBeanToInsertHandler handler = new PgsqlBeanToInsertHandler(valueHandler);
        PgAccountEntity account = new PgAccountEntity();
        account.setAccountName("u1");
        account.setId(9L);
        account.setBalance(new BigDecimal("1.00"));
        account.setRegisterDate(java.time.LocalDate.of(2026, 1, 2));

        String sql = handler.buildInsertSql(account);
        // 列顺序 = 声明顺序，且 id 被跳过（它的值由 IDENTITY 生成）
        assertEquals("INSERT INTO \"t_pg_account\" (\"account_name\", \"balance\", \"vip_level\", "
                + "\"last_login_time\", \"register_date\", \"frozen\", \"tags\") "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)", sql);
        assertEquals(7, handler.buildInsertParams(account).length);
        assertEquals("id", handler.getIdentityColumn(account).getColumnName(), "按列名取生成键的前提");
    }

    /**
     * 用例⑦：UPDATE 的 SET/WHERE 切分与参数顺序。
     * <p>主键只出现在 WHERE，参数数组是"SET 段在前、主键段在后"——
     * 这是绑定错位最容易出事的地方，因此连同参数个数一起断言。</p>
     */
    @Test
    void updatePutsPkOnlyInWhere() {
        PgsqlBeanToStatementHandler handler = new PgsqlBeanToStatementHandler(valueHandler);
        PgAccountEntity account = new PgAccountEntity();
        account.setId(3L);
        account.setAccountName("u3");

        String sql = handler.buildUpdateSql(account);
        assertTrue(sql.endsWith("WHERE \"id\" = ?"), sql);
        assertFalse(sql.substring(0, sql.indexOf("WHERE")).contains("\"id\""), "主键不能出现在 SET 里: " + sql);
        assertEquals(8, handler.buildUpdateParams(account).length, "7 个业务列 + 1 个主键");
    }

    /**
     * 用例⑧：复合主键的 SELECT / DELETE 把两个主键列都写进 WHERE。
     * <p>只按首列定位会查回/删掉多行（一个订单的多条明细），是静默的数据损失，
     * 所以这一条必须锁在文本层面。</p>
     */
    @Test
    void compositeKeyExpandsToAllPkColumns() {
        PgsqlBeanToStatementHandler handler = new PgsqlBeanToStatementHandler(valueHandler);
        TableInfo tableInfo = EntityParser.parse(PgOrderItemEntity.class);

        assertEquals("SELECT * FROM \"t_pg_order_item\" WHERE \"order_id\" = ? AND \"sku_code\" = ?",
                handler.buildSelectByIdSql(tableInfo));

        PgOrderItemEntity item = new PgOrderItemEntity();
        item.setOrderId(1L);
        item.setSkuCode("SKU-1");
        assertEquals("DELETE FROM \"t_pg_order_item\" WHERE \"order_id\" = ? AND \"sku_code\" = ?",
                handler.buildDeleteByIdSql(item));
        assertEquals(2, handler.buildDeleteByIdParams(item).length);
    }

    /**
     * 用例⑨：无主键实体拒绝生成 UPDATE/DELETE，绝不退化成全表操作。
     */
    @Test
    void noPrimaryKeyIsRejectedNotSilent() {
        PgsqlBeanToStatementHandler handler = new PgsqlBeanToStatementHandler(valueHandler);
        TableInfo tableInfo = handTable("t_no_pk");
        tableInfo.getColumns().put("c", handColumn("c", "TEXT"));

        assertThrows(IllegalArgumentException.class, () -> handler.buildSelectByIdSql(tableInfo));
    }

    /**
     * 用例⑩：分页子句按需追加，"只有偏移"时不补 MySQL 的哨兵 LIMIT。
     * <p>MySQL 的 {@code LIMIT 18446744073709551615} 在 PG 会 22001（超出 bigint），
     * 而 PG 允许只写 OFFSET，所以三种组合的参数个数也必须跟着变。</p>
     */
    @Test
    void pagingAppendsOnlyTheClausesPresent() {
        PgsqlBeanToStatementHandler handler = new PgsqlBeanToStatementHandler(valueHandler);

        StringBuilder onlyLimit = new StringBuilder();
        List<Object> limitParams = new ArrayList<>();
        handler.appendPaging(onlyLimit, limitParams, 10, 0);
        assertEquals(" LIMIT ?", onlyLimit.toString());
        assertEquals(List.of(10), limitParams);

        StringBuilder onlyOffset = new StringBuilder();
        List<Object> offsetParams = new ArrayList<>();
        handler.appendPaging(onlyOffset, offsetParams, null, 20);
        assertEquals(" OFFSET ?", onlyOffset.toString(), "PG 可以只写 OFFSET，不需要哨兵 LIMIT");
        assertEquals(List.of(20), offsetParams);

        StringBuilder both = new StringBuilder();
        List<Object> bothParams = new ArrayList<>();
        handler.appendPaging(both, bothParams, 10, 20);
        assertEquals(" LIMIT ? OFFSET ?", both.toString());
        assertEquals(List.of(10, 20), bothParams, "参数顺序必须与子句出现顺序一致");
    }

    /**
     * 用例⑪：查询 DSL 走的标识符出口也换成双引号小写口径。
     * <p>{@code quote()} 是 {@code SelectSqlBuilder} 拼列名/WHERE/ORDER BY 的唯一出口，
     * 覆盖它等于把整条 DSL 的引号口径换掉；COUNT 语句由默认方法复用同一出口，一并断言。</p>
     * <p>顺带锁住一件事：{@code quote()} <b>只做引用，不做驼峰转下划线</b>（传 {@code accountName}
     * 得到的是 {@code "accountname"}）。列名转换是 EntityParser 的职责，DSL 拿到的已经是
     * {@code account_name}；若这里改成两套口径共存，同一实体在 MySQL 与 PG 上的列名就会分叉。</p>
     */
    @Test
    void dslUsesPgIdentifierQuoting() {
        PgsqlBeanToStatementHandler handler = new PgsqlBeanToStatementHandler(valueHandler);
        TableInfo tableInfo = EntityParser.parse(PgAccountEntity.class);

        assertEquals("\"account_name\"", handler.quote("account_name"));
        assertEquals("\"accountname\"", handler.quote("accountName"), "只引用，不转换命名风格");
        assertEquals("SELECT COUNT(*) FROM \"t_pg_account\"", handler.buildCountSql(tableInfo));
        assertEquals("SELECT * FROM \"t_pg_account\"", handler.buildSelectAllSql(tableInfo));
    }
}
